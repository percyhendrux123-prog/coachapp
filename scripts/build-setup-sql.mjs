#!/usr/bin/env node
// Builds supabase/setup/database.sql: the whole database in one file that a coach can paste
// into the Supabase SQL editor and run once. It is generated, never edited by hand.
//
//   node scripts/build-setup-sql.mjs          write the file
//   node scripts/build-setup-sql.mjs --check  exit 1 if the committed file is out of date
//
// Contents, in order:
//   1. a guard that stops (and changes nothing) if the database is already set up,
//      then the two extensions the schema needs (pg_net, pg_cron)
//   2. every file in supabase/migrations/, in filename order, unchanged
//   3. supabase/seed.sql (generic reference vocabulary)
//   4. rows in supabase_migrations.schema_migrations, so a developer can later run
//      `supabase db push` against the same project and only new migrations apply
//
// The SQL editor sends the file as one request, which Postgres runs as one transaction:
// if any statement fails, nothing is kept and the coach can simply run it again.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "supabase/migrations");
const seedPath = join(root, "supabase/seed.sql");
const outPath = join(root, "supabase/setup/database.sql");
export const SQL_EDITOR_SAFE_BYTES = 900_000;

export function buildSetupSql() {
  const files = readdirSync(migrationsDir).filter((f) => /^\d+_.+\.sql$/.test(f)).sort();
  const parts = [];

  parts.push(`-- Coach app database setup. GENERATED by scripts/build-setup-sql.mjs. Do not edit by hand.
--
-- How to use (no terminal needed):
--   Supabase dashboard -> your project -> SQL Editor (left sidebar) -> New query (+),
--   paste this whole file, press Run. If a "Potential issues detected" box appears, click
--   "Run and enable RLS". Expect a one-row result: Setup complete.
--
-- It runs as one transaction. If anything fails, nothing is kept and you can run it again.
-- Running it on a database that is already set up stops at the first line and changes nothing.

do $guard$
begin
  if to_regclass('public.tenants') is not null then
    raise exception 'This database is already set up (table public.tenants exists). Nothing was changed.';
  end if;
end
$guard$;

-- Extensions the schema relies on. New Supabase projects have them available but off.
-- pg_net makes HTTP calls from the database (coach push, scheduled jobs);
-- pg_cron runs the scheduled jobs.
create extension if not exists pg_net with schema extensions;
create extension if not exists pg_cron with schema pg_catalog;
grant usage on schema cron to postgres;
`);

  for (const f of files) {
    const body = readFileSync(join(migrationsDir, f), "utf8").replace(/\s+$/, "");
    parts.push(`-- ===== migration ${f} =====\n${body}\n`);
    // Each migration normally runs in its own session. The initial schema (a pg_dump) sets
    // an empty search_path and turns body checks off for that session; put the defaults back
    // so every later file runs exactly as it would on its own.
    parts.push(`reset search_path;\nreset check_function_bodies;\nreset client_min_messages;\nreset row_security;\n`);
  }

  const seed = readFileSync(seedPath, "utf8").replace(/\s+$/, "");
  parts.push(`-- ===== seed.sql =====\n${seed}\n`);

  const rows = files.map((f) => {
    const m = f.match(/^(\d+)_(.+)\.sql$/);
    return `  ('${m[1]}', '${m[2].replace(/'/g, "''")}')`;
  });
  parts.push(`-- ===== migration history (lets \`supabase db push\` skip what is already applied) =====
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (
  version text not null primary key,
  statements text[],
  name text
);
-- Only the database owner (the CLI) reads this table; row level security keeps the API out.
alter table supabase_migrations.schema_migrations enable row level security;
insert into supabase_migrations.schema_migrations (version, name) values
${rows.join(",\n")}
on conflict (version) do nothing;

-- The SQL editor shows the result of the last statement.
select 'Setup complete' as result;
`);

  return parts.join("\n");
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const sql = buildSetupSql();
  // The Supabase SQL editor refuses queries over about 0.98 MiB ("Query is too large to be run
  // via the SQL Editor"). Stay well under it so a coach can paste the file in one go.
  if (Buffer.byteLength(sql) > SQL_EDITOR_SAFE_BYTES) {
    console.error(`supabase/setup/database.sql would be ${Buffer.byteLength(sql)} bytes, over the ${SQL_EDITOR_SAFE_BYTES}-byte SQL editor budget. Split it into two files and update SETUP.md.`);
    process.exit(1);
  }
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(outPath, "utf8"); } catch { /* missing counts as stale */ }
    if (current !== sql) {
      console.error("supabase/setup/database.sql is out of date. Run: node scripts/build-setup-sql.mjs");
      process.exit(1);
    }
    console.log("supabase/setup/database.sql is up to date.");
  } else {
    writeFileSync(outPath, sql);
    console.log(`Wrote supabase/setup/database.sql (${Buffer.byteLength(sql)} bytes).`);
  }
}
